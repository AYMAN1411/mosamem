#!/usr/bin/env node
// M9: runs tools/psd-roundtrip.js inside the running debug app (MOSAMEM_HARNESS=1, window in front:
// tools/front.sh on) over every .psd in a folder, then writes the raw results and a report.
//   node tools/psd-report.mjs          the public fixtures → docs/psd-roundtrip-m9.json, docs/psd-report.md
//   node tools/psd-report.mjs <dir>    your own files → <dir>/results.json, <dir>/report.md
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const own = process.argv[2] ? resolve(process.argv[2]) : null;
const dir = own ?? join(root, 'tests/psd-fixtures/psd-tools');
if (!existsSync(dir)) {
  console.error(own ? `no folder ${own}` : 'no fixtures: run tools/fetch-psd-fixtures.sh first');
  process.exit(1);
}
const jsonOut = own ? join(own, 'results.json') : join(root, 'docs/psd-roundtrip-m9.json');
const mdOut = own ? join(own, 'report.md') : join(root, 'docs/psd-report.md');
const files = readdirSync(dir).filter((f) => /\.ps[db]$/i.test(f)).sort().map((f) => join(dir, f));
const script = readFileSync(join(root, 'tools/psd-roundtrip.js'), 'utf8').replace('__FILES__', JSON.stringify(files));
const res = await fetch('http://127.0.0.1:47811/', { method: 'POST', body: script });
const out = JSON.parse(await res.text());
if (!out.ok) {
  console.error(out.error);
  process.exit(1);
}
const results = out.value;
writeFileSync(jsonOut, JSON.stringify(results, null, 1) + '\n');

// ---- classify ----
const exact = (v) => typeof v === 'object' && v.within1 >= 99.9;
const close = (v) => typeof v === 'object' && v.within8 >= 99;
const roundTripOk = (r) => r.structureKept && typeof r.reopened === 'object' && r.reopened.max <= 1;
const groups = { error: [], noRef: [], exact: [], close: [], differs: [] };
for (const r of results) {
  if (r.error) groups.error.push(r);
  else if (typeof r.vsPhotoshop !== 'object') groups.noRef.push(r);
  else if (exact(r.vsPhotoshop)) groups.exact.push(r);
  else if (close(r.vsPhotoshop)) groups.close.push(r);
  else groups.differs.push(r);
}
const opened = results.filter((r) => !r.error);
const rtOk = opened.filter(roundTripOk);

const fmt = (v) => (typeof v === 'object' ? `${v.within1}% / ${v.within8}% (mean ${v.mean}, max ${v.max})` : String(v));
const warn = (r) => (r.warnings ?? []).map((w) => (w.params ? `${w.key} (${Object.values(w.params).join(', ')})` : w.key)).join('; ');
const row = (r) => `| ${r.file} | ${r.size ?? ''} | ${fmt(r.vsPhotoshop)} | ${roundTripOk(r) ? 'yes' : r.structureKept ? `pixels: max ${r.reopened?.max}` : 'structure changed'} | ${warn(r) || '—'} |`;
const table = (rs) => ['| file | size | vs Photoshop: ≤1 / ≤8 levels | own round trip kept | not carried over |', '|---|---|---|---|---|', ...rs.map(row)].join('\n');

const md = `# PSD report (M9)

Generated by \`tools/psd-report.mjs\` on ${new Date().toISOString().slice(0, 10)}, from ${own ? `the ${results.length} files in ${basename(own)}` : `the ${results.length} public test files of
psd-tools (MIT; fetched by \`tools/fetch-psd-fixtures.sh\`, not committed)`}. Raw numbers: \`${basename(jsonOut)}\`.

For every file:

1. **Open**: ag-psd reads it in a worker, Mosamem builds its layers, and the engine renders them.
2. **vs Photoshop**: that render is compared with the flattened image Photoshop stored in the file
   (RGB over white, so colors under full transparency don't count). The columns give the share of
   pixels within 1 and within 8 levels (of 255), and the mean and largest difference.
3. **Own round trip**: Mosamem saves the document as PSD, opens that again, and checks that the
   layer structure and the rendering are unchanged.

## Summary

| | files |
|---|---|
| opened | ${opened.length} of ${results.length} |
| own round trip kept (structure and pixels) | ${rtOk.length} of ${opened.length} |
| match Photoshop's image (≥ 99.9% within 1 level) | ${groups.exact.length} |
| close (≥ 99% within 8 levels) | ${groups.close.length} |
| differ | ${groups.differs.length} |
| no image to compare with (saved without "Maximize Compatibility") | ${groups.noRef.length} |
| could not be opened | ${groups.error.length} |

## Could not be opened

${groups.error.map((r) => `- ${r.file}: ${r.error}`).join('\n') || 'None.'}

CMYK and other non-RGB color modes are not read by ag-psd; Mosamem says so and suggests converting to RGB.

## Differ from Photoshop

${table(groups.differs)}

What is known about these (see "Known gaps" below for the features):

- **fill_adjustments, passthrough_fill_adjustment, clipping-mask2, layer_mask_data, layer_comps**: adjustment layers
  (Levels, Curves, Hue/Saturation, …) are Mosamem's own formulas, written from Adobe's public help
  pages; Photoshop's exact math is not public. These files are the calibration data for them.
- **effect-stroke-gradient, stroke-*, layer_effects, pen-text**: gradient and pattern strokes, inner glow,
  bevel, satin and pattern overlay are not implemented; strokes and glows are close but not exact.
- **artboard-bgcolor, patterns, gradient-fill, advanced-blending**: artboard backgrounds, pattern fills,
  gradient fill layers and "blend if" ranges are not implemented.
- **clipping-mask4**, **passthrough_fill_blendmode, passthrough_clipping_mask_blendmode**: knockout and
  pass-through groups with fill opacity behave differently from Mosamem's.

## Close to Photoshop

${table(groups.close)}

## Match Photoshop

${table(groups.exact)}

## No image to compare with

Photoshop stores a blank flattened image when "Maximize Compatibility" is off, so only the own
round trip is checked here.

${table(groups.noRef)}

## Known gaps

- Vector shapes and vector masks are opened as pixel layers with pixel masks (no path editing).
  Shapes saved without pixels are drawn from their paths; the edges can differ by a level or two.
- Smart objects keep their pixels (no linked or embedded document editing).
- Text keeps Photoshop's pixels until edited; editing reflows it with Mosamem's fonts.
- 16- and 32-bit files are converted to 8-bit on opening.
- Not yet: inner glow, bevel and emboss, satin, pattern overlay, gradient/pattern strokes,
  "blend if", knockout, artboards, layer comps, CMYK.
- The files here come from one open-source project's test suite. Files from the user's own
  Photoshop are the next check: see \`docs/psd-checklist.md\`.
`;
writeFileSync(mdOut, own ? md.replace(/\n## Differ from[\s\S]*?(?=\n## Close)/, (m) => m.replace(/\nWhat is known[\s\S]*$/, '\n')) : md);
console.log(`opened ${opened.length}/${results.length}; round trip ${rtOk.length}; exact ${groups.exact.length}, close ${groups.close.length}, differ ${groups.differs.length}, no reference ${groups.noRef.length}, errors ${groups.error.length}`);
